def texture(im,body,shade,light,region):
 """Place defined mineral flakes only on the supplied body pigments."""
 base=im.copy();paint=Image.new('RGBA',im.size);d=Pen(paint)
 for i,(x,y,u,v) in enumerate(CLUSTERS):
  # Three connected flake fragments follow each authored mineral deposit.
  # Fine edge breakup, rather than a broad repeated oval.
  d.r((x,y,x+3,y+1),*shade)
  d.r((x+2,y+2,x+5,y+2),*shade)
  d.r((x+5,y-2,max(x+7,u),y-1),*light)
  d.r((x+6,y-1,max(x+8,u+2),y),*light)
  d.r((x-3,y+4,x,y+5),*shade)
  d.r((x-1,y+5,x+2,y+5),*shade)
 x0,y0,x1,y1=region;allowed={tuple(bytes.fromhex(c(*s)[1:])) for s in body}
 for y in range(y0,y1):
  for x in range(x0,x1):
   q=paint.getpixel((x,y))
   if q[3] and base.getpixel((x,y))[:3] in allowed:im.putpixel((x,y),q)

