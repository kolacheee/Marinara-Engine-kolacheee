class Pencil(Pen):
 def __init__(self,im,origin=(0,0)):
  super().__init__(im);self.x,self.y=origin
 def r(self,b,r,s):
  x,y,u,v=b;super().r((x+self.x,y+self.y,u+self.x,v+self.y),r,s)
 def p(self,t,r,s,edge=None):
  t=' '.join(f'{x+self.x},{y+self.y}' for x,y in pts(t));super().p(t,r,s,edge)
 def l(self,t,r,s):
  t=' '.join(f'{x+self.x},{y+self.y}' for x,y in pts(t));super().l(t,r,s)
 def paths(self,t,r,s):
  for a in t.split(';'):
   if a.strip():self.p(a.strip(),r,s)

