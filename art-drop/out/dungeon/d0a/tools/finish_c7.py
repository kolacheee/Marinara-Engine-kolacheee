from PIL import Image,ImageDraw
from draw_proofs import c,pts

def patches(im,data,ink,offset=(0,0),clip=None):
 layer=Image.new('RGBA',im.size);d=ImageDraw.Draw(layer)
 for path in data.split(';'):
  if path.strip():d.polygon([(x+offset[0],y+offset[1]) for x,y in pts(path)],fill=c(*ink))
 if clip:
  for y in range(im.height):
   for x in range(im.width):
    if not clip(x,y):layer.putpixel((x,y),(0,0,0,0))
 im.alpha_composite(layer)
def stroke(im,data,ink,width=1):
 d=ImageDraw.Draw(im)
 for path in data.split(';'):
  if path.strip():d.line(pts(path),fill=c(*ink),width=width)
def rect(im,b,ink):ImageDraw.Draw(im).rectangle(b,fill=c(*ink))

