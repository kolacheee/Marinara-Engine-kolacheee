def finish(n,f,w):
 # Material selection is explicit. Only stone gets the stone grain field.
 if n in ('keep','crypt','yard'):
  top={'keep':('iron',2),'crypt':('dark-masonry',2),'yard':('yard-cobble',1)}[n]
  face={'keep':('limestone',2),'crypt':('dark-masonry',3),'yard':('yard-cobble',2)}[n]
  # Broken edges run into finer grain at the same value as the main plane.
  patches(w,GRAIN_A,top,(0,8),lambda x,y:8<=y<48)
  patches(w,GRAIN_B,face,(0,48),lambda x,y:48<=y<95)
 if n in ('keep','crypt'):
  base={'keep':('limestone',3),'crypt':('dark-masonry',4)}[n]
  mid={'keep':('iron',3),'crypt':('bone',2)}[n]
  for data,y in [(GRAIN_A,0),(GRAIN_B,48)]:
   patches(f,data,mid,(0,y),lambda x,yy:x%48>1 and yy%48>1)
  patches(f,GRAIN_A,base,(0,96),lambda x,y:x%48>1 and y%48>1)
  # Bottom flags receive a distinct network of shorter connected chips.
  patches(f,GRAIN_B,mid,(0,94),lambda x,y:98<=y<144 and x%48>1)
 if n=='temple':
  patches(w,GRAIN_A,('marble',1),(0,8),lambda x,y:8<=y<48)
  patches(w,GRAIN_B,('sandstone',2),(0,48),lambda x,y:48<=y<95)
 if n=='manor':
  # Darker plaster flecks link pale cloud edges; timber retains its own grain.
  patches(w,GRAIN_B,('plaster',2),(0,47),lambda x,y:49<=y<88 and (6<=x<=68 or 75<=x<=137))
  stroke(w,'2,12 10,12 10,13 17,13;2,19 9,19 9,20 16,20 16,21 24,21;1,26 10,26 10,27 18,27;2,34 8,34 8,33 15,33;3,43 15,43 15,42 24,42;24,16 31,16 31,17 38,17;21,24 29,24 29,25 37,25;23,31 30,31 30,30 36,30;30,44 38,44 38,42 45,42;43,12 51,12 51,13 58,13;63,11 71,11 71,12 77,12;63,20 70,20 70,21 77,21;62,35 67,35 67,36 72,36;55,43 63,43 63,44 70,44;79,26 85,26 85,28 91,28;87,37 95,37 95,38 104,38;90,10 98,10 98,11 104,11;105,19 113,19 113,20 120,20;106,28 114,28 114,29 123,29;122,8 132,8 132,9 140,9;126,24 134,24 134,25 142,25;127,40 135,40 135,41 143,41',('timber',3))
 if n=='dungeon_sewer':
  patches(w,GRAIN_B,('brick',2),(0,6),lambda x,y:8<=y<48)
  # Edge losses meet mortar. Blocks have different area of remaining glaze.
  patches(f,GRAIN_A,('brick',3),(0,0),lambda x,y:x%24>0 and y%12>0)
  patches(f,GRAIN_B,('brick',3),(0,48),lambda x,y:x%24>0 and y%12>0)
  patches(f,GRAIN_A,('sewer-water',3),(0,94),lambda x,y:y>=97 and x%24>0 and y%12>0)
 if n=='cave_rock':
  patches(w,GRAIN_A,('grey-brown-rock',2),(0,8),lambda x,y:8<=y<48)
  patches(w,GRAIN_B,('mud',3),(0,48),lambda x,y:48<=y<95)
 if n=='cave_crystal':
  patches(w,GRAIN_B,('dark-rock',3),(0,6),lambda x,y:8<=y<48)
  patches(w,GRAIN_A,('dark-rock',3),(0,47),lambda x,y:48<=y<95)
 if n=='cave_lava':
  patches(w,GRAIN_A,('basalt',3),(0,8),lambda x,y:8<=y<48)
  patches(w,GRAIN_B,('basalt',4),(0,47),lambda x,y:48<=y<95)

