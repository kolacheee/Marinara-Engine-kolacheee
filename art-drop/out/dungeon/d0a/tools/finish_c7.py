def micro(im,ink,offset=(0,0),clip=None):
 col=tuple(bytes.fromhex(c(*ink)[1:]))+(255,)
 for mark in MICRO.split(';'):
  if not mark.strip():continue
  pos,rows=mark.strip().split(':');a,b=map(int,pos.split(','));a+=offset[0];b+=offset[1]
  for y,row in enumerate(rows.split('/')):
   for x,v in enumerate(row):
    if v=='#' and 0<=a+x<im.width and 0<=b+y<im.height and (clip is None or clip(a+x,b+y)):im.putpixel((a+x,b+y),col)
def recolour(im,pairs,region=lambda x,y:True):
 lookup={tuple(bytes.fromhex(c(*a)[1:]))+(255,):tuple(bytes.fromhex(c(*b)[1:]))+(255,) for a,b in pairs}
 for y in range(im.height):
  for x in range(im.width):
   if region(x,y) and im.getpixel((x,y)) in lookup:im.putpixel((x,y),lookup[im.getpixel((x,y))])

