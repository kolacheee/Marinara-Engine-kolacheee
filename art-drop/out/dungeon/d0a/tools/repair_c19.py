def assemble():
    record={}
    for n in NAMES:
        if n=='manor':top,face,floor=manor()
        elif n.startswith('cave_'):top,face,floor=cave(n)
        else:
            top,face=masonry(n);floor=yard_floor() if n=='yard' else built_floor(n)
        edits={tag:clean_small(im) for tag,im in [('top',top),('face',face),('floor',floor)]}
        wall=canvas((144,96),'void-mass:2');wall.paste(top,(0,8));wall.paste(face,(0,48))
        line(wall,[(0,95),(143,95)],S[n][1][0]+':1')
        proof=Image.new('RGBA',(144,144));proof.paste(wall);proof.paste(floor,(0,96))
        proof.alpha_composite(Image.open(REVIEW/f'C-layer-{n}-prop.png').convert('RGBA'),(86,96))
        for tag,im in [('top',top),('face',face),('floor',floor),('wall',wall),('proof',proof)]:im.save(REVIEW/f'C19-{n}-{tag}.png')
        record[n]={'method':'native authored contours and clusters','cleanup_pixels':{k:len(v) for k,v in edits.items()}}
    (REVIEW/'C19-assembly.json').write_text(json.dumps(record,indent=2)+'\n')
    for page in range(2):
        sheet=Image.new('RGB',(1520,320),'#222630');d=ImageDraw.Draw(sheet)
        for i,n in enumerate(NAMES[page*5:page*5+5]):
            d.text((i*304+8,4),n,fill='white');im=Image.open(REVIEW/f'C19-{n}-proof.png')
            sheet.paste(im.resize((288,288),Image.Resampling.NEAREST),(i*304+8,24))
        sheet.save(REVIEW/f'C19-proof-contact-{page}.png')
if __name__=='__main__':assemble()
