def masonry(n):
    ramps={
      'keep':('limestone:1','iron:2','limestone:2','limestone:3'),
      'temple':('sandstone:1','marble:1','sandstone:2','sandstone:3'),
      'crypt':('dark-masonry:2','dark-masonry:3','dark-masonry:4','dark-masonry:5'),
      'dungeon_sewer':('brick:1','brick:2','brick:3','brick:4'),
      'yard':('yard-cobble:1','roof-slate:2','yard-cobble:2','yard-cobble:3')}
    joint,shade,body,edge=ramps[n]
    face=canvas((144,47),joint)
    for i,(x,y,w,h,shape,lip) in enumerate(STONES):
        poly(face,move(shape,x,y),body)
        poly(face,move(lip,x,y),edge)
        # Lower return is a recess within the stone; the mortar remains below.
        # Unequal native runs follow the authored chips above.
        end=w-(4 if i in (0,3,6,9) else 2)
        line(face,[(x+6,y+12),(x+end,y+12)],shade)
        if i in (1,5,8,10):
            poly(face,move([(w-12,9),(w-7,9),(w-7,8),(w-2,8),(w-2,11),(w-12,11)],x,y),shade)
    if n=='dungeon_sewer':
        face=canvas((144,47),joint)
