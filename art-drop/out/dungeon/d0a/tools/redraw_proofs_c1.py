class Pen:
 def __init__(self,im): self.im=im; self.d=ImageDraw.Draw(im)
 def r(self,b,r,s): self.d.rectangle(b,fill=c(r,s))
 def p(self,t,r,s,edge=None): self.d.polygon(pts(t),fill=c(r,s),outline=(c(*edge) if isinstance(edge,tuple) else c(r,edge)) if edge else None)
 def l(self,t,r,s): self.d.line(pts(t),fill=c(r,s),width=1)
 def ls(self,ts,r,s):
  for t in ts:self.l(t,r,s)
 def ps(self,ts,r,s):
  for t in ts:self.p(t,r,s)

