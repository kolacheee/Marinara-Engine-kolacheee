from redraw_critic21 import canvas,poly,line,box


def wrap_poly(im,r,path):
    # Continue the same authored shape over a tile boundary at native resolution.
    points=[tuple(map(int,p.split(','))) for p in path.split()]
    from PIL import ImageDraw
    from draw_proofs import c
    ramp,step=r.split(':')
    for dx in (-288,0,288):
        for dy in (-288,0,288):ImageDraw.Draw(im).polygon([(x+dx,y+dy) for x,y in points],fill=c(ramp,int(step)))


