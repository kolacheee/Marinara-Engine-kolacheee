def col(tag):
    r,s=tag.split(':');return c(r,int(s))

def canvas(size,tag):return Image.new('RGBA',size,col(tag))
def poly(im,tag,path):ImageDraw.Draw(im).polygon(pts(path),fill=col(tag))
def line(im,tag,path,width=1):ImageDraw.Draw(im).line(pts(path),fill=col(tag),width=width)
def box(im,tag,b):ImageDraw.Draw(im).rectangle(b,fill=col(tag))
def polygons(im,tag,paths):
    for path in paths:poly(im,tag,path)

